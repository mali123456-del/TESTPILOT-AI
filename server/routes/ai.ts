aiRouter.post('/agents/:id/run', requireAuth, requireRole('tester'), async (req: AuthedRequest, res) => {
  const agent = agentById(req.params.id);
  if (!agent) return res.status(404).json({ error: 'Unknown agent' });
  const parsed = z.object({ input: z.string().max(4000).optional(), projectId: z.string().optional(), runId: z.string().optional() }).safeParse(req.body ?? {});
  if (!parsed.success) return res.status(400).json({ error: 'Invalid agent input' });
  const db = getDb();
  const workspaceId = req.user!.workspaceId;
  const input = parsed.data.input ?? '';
  // Execution limit per hour
  const hourAgo = Date.now() - 3600_000;
  const recent = db.agentRuns.filter((r) => r.agentId === agent.id && r.workspaceId === workspaceId && new Date(r.createdAt).getTime() > hourAgo).length;
  if (recent >= agent.maxRunsPerHour) return res.status(429).json({ error: `Hourly limit of ${agent.maxRunsPerHour} runs reached for ${agent.name}` });

  const agentRun = {
    id: id('agr'),
    workspaceId,
    agentId: agent.id,
    projectId: parsed.data.projectId,
    input,
    status: 'completed' as const,
    createdAt: now(),
  };
  const metrics = computeMetrics(workspaceId);
  let output = '';
  let approvalId: string | undefined;

  if (agent.id === 'planner') {
    output = `Plan for: ${input || 'current release'}\n\nPriority order:\n1. Critical failures (${metrics.criticalFailures})\n2. Security suite\n3. Payment and auth regressions\n4. Flaky quarantine (${metrics.flaky.length})`;

  } else if (agent.id === 'case-generator' || agent.id === 'api-agent') {
    const requirement = input || 'Verify the checkout API contract and validation behaviour';
    const { cases, provider } = await generateCases(requirement, 5);
    output = `Drafted ${cases.length} cases with the ${provider} provider. Approval is required before they are added to a suite.`;
    const approval = {
      id: id('apr'),
      workspaceId,
      kind: 'ai.case-generation',
      title: `${agent.name}: ${cases.length} drafted cases`,
      payload: { suiteId: undefined, requirement, cases },
      requestedBy: req.user!.name,
      status: 'pending' as const,
      createdAt: now(),
    };
    db.approvals.unshift(approval);
    approvalId = approval.id;
    agentRun.status = 'awaiting_approval' as never;
  } else if (agent.id === 'automation-engineer') {
    output = `Suggested workflow for ${input || 'the selected suite'}:\n1. Run smoke suite\n2. On failure → stop and notify\n3. Run regression suite with 2 retries (2s backoff)\n4. Request QA lead approval\n5. Notify #releases\n\nConcurrency: 3 workers. Timeout: 15 minutes.`;
  } else if (agent.id === 'bug-detector') {
    const runs = db.runs.filter((r) => r.workspaceId === workspaceId).slice(0, 10);
    const failures = runs.flatMap((r) => r.results.filter((x) => x.status === 'failed' || x.status === 'error').map((x) => ({ ...x, runId: r.id })));
    const grouped = new Map<string, typeof failures>();
    for (const f of failures) grouped.set(f.caseId, [...(grouped.get(f.caseId) ?? []), f]);
    const candidates = [...grouped.entries()].filter(([, v]) => v.length >= 1).slice(0, 5);
    output = candidates.length
      ? `Detected ${candidates.length} recurring failure candidate(s):\n${candidates.map(([, v]) => `- ${v[0].title} — ${v.length} occurrence(s) · latest: ${v[0].message?.slice(0, 120)}`).join('\n')}\n\nApprove to create defect records.`
      : 'No recurring failure pattern detected in the last 10 runs.';
    if (candidates.length) {
      const approval = {
        id: id('apr'),
        workspaceId,
        kind: 'ai.bug-drafts',
        title: `${agent.name}: ${candidates.length} defect draft(s)`,
        payload: {
          bugs: candidates.map(([caseId, v]) => ({
            title: `Recurring failure: ${v[0].title}`,
            description: v[0].message ?? 'Failure detected by the Bug Detection Agent.',
            severity: 'high',
            caseId,
          })),
          projectId: parsed.data.projectId,
        },
        requestedBy: req.user!.name,
        status: 'pending' as const,
        createdAt: now(),
      };
      db.approvals.unshift(approval);
      approvalId = approval.id;
      agentRun.status = 'awaiting_approval' as never;
    }
  } else if (agent.id === 'debugger') {
    const run = parsed.data.runId ? db.runs.find((r) => r.id === parsed.data.runId) : db.runs.find((r) => r.workspaceId === workspaceId && r.status !== 'passed');
    const failures = run?.results.filter((r) => r.status === 'failed' || r.status === 'error') ?? [];
    output = failures.length
      ? localFailureAnalysis(failures.map((f) => ({ title: f.title, message: f.message, type: f.type, durationMs: f.durationMs })))
      : 'No failing run available. Trigger a run first.';
  } else if (agent.id === 'performance-analyst') {
    const perf = db.perfRuns.filter((p) => p.workspaceId === workspaceId).slice(0, 5);
    output = perf.length
      ? perf.map((p) => `- ${p.url}: p95 ${p.metrics?.p95 ?? 'n/a'}ms, ${p.metrics?.rps ?? 0} req/s, ${p.metrics?.errorRate ?? 0}% errors`).join('\n')
      : 'No performance runs recorded yet. Create a bounded load profile in the Performance workspace.';
  } else if (agent.id === 'security-reviewer') {
    const scans = db.securityScans.filter((s) => s.workspaceId === workspaceId).slice(0, 5);
    output = scans.length
      ? scans.map((s) => `- ${s.url}: score ${s.score}/100 with ${s.findings.length} finding(s)`).join('\n')
      : 'No security scans recorded. Run a passive scan in the Security workspace.';
  } else if (agent.id === 'report-writer') {
    output = `Quality snapshot\n\n- Pass rate ${metrics.passRate}%\n- Coverage ${metrics.coverage}%\n- Open defects ${metrics.openBugs} (critical ${metrics.criticalBugs})\n- Flaky cases ${metrics.flaky.length}\n- Release readiness ${metrics.readiness}/100\n\n${localChat('release readiness', workspaceSummary(workspaceId))}`;
  }

  const finalStatus: AgentRun['status'] = approvalId ? 'awaiting_approval' : 'completed';
  const record: AgentRun = { ...agentRun, status: finalStatus, output, artifacts: approvalId ? [approvalId] : [] };
  db.agentRuns.unshift(record);
  saveDb();
  audit(workspaceId, req.user!.name, 'agent.run', agent.name, { approvalId, input: input.slice(0, 160) }, req.ip);
  res.status(201).json({ ...record, approvalId });
});

