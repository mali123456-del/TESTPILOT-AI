aiRouter.post('/duplicates', requireAuth, (req: AuthedRequest, res) => {
  const parsed = z.object({ projectId: z.string().optional(), threshold: z.number().min(0.4).max(0.95).optional() }).safeParse(req.body ?? {});
  const threshold = parsed.success ? (parsed.data.threshold ?? 0.62) : 0.62;
  const db = getDb();
  const cases = db.cases.filter((c) => c.workspaceId === req.user!.workspaceId && (!parsed.success || !parsed.data.projectId || c.projectId === parsed.data.projectId));
  const tokens = (s: string) => new Set(s.toLowerCase().replace(/[^a-z0-9 ]/g, ' ').split(/\s+/).filter((w) => w.length > 2));
  const jaccard = (a: Set<string>, b: Set<string>) => {
    const inter = [...a].filter((x) => b.has(x)).length;
    const union = new Set([...a, ...b]).size;
    return union ? inter / union : 0;
  };
  const pairs: Array<{ a: string; b: string; similarity: number; titles: [string, string] }> = [];
  for (let i = 0; i < cases.length; i += 1) {
    for (let j = i + 1; j < cases.length; j += 1) {
      const sim = jaccard(tokens(`${cases[i].title} ${cases[i].expected ?? ''}`), tokens(`${cases[j].title} ${cases[j].expected ?? ''}`));
      if (sim >= threshold) pairs.push({ a: cases[i].id, b: cases[j].id, similarity: Math.round(sim * 100), titles: [cases[i].title, cases[j].title] });
    }
  }
  res.json({ threshold, pairs: pairs.sort((x, y) => y.similarity - x.similarity).slice(0, 20) });
});

aiRouter.post('/plan', requireAuth, (req: AuthedRequest, res) => {
  const parsed = z.object({ goal: z.string().min(5).max(2000), projectId: z.string().optional() }).safeParse(req.body);
  if (!parsed.success) return res.status(400).json({ error: 'Describe the goal' });
  const db = getDb();
  const project = parsed.data.projectId ? db.projects.find((p) => p.id === parsed.data.projectId && p.workspaceId === req.user!.workspaceId) : undefined;
  const metrics = computeMetrics(req.user!.workspaceId);
  const gaps = metrics.coverageByType.filter((c) => c.executed === 0).map((c) => c.type);
  const plan = [
    `## Test plan — ${project?.name ?? 'workspace'}`,
    '',
    `**Goal:** ${parsed.data.goal}`,
    '',
    '### Risk-based scope',
    `1. **Critical paths** — authentication, payments and data mutation. ${metrics.criticalFailures ? `${metrics.criticalFailures} critical failure(s) are already recorded and must be closed first.` : 'No open critical failures recorded.'}`,
    `2. **Stability** — ${metrics.flaky.length} flaky case(s) identified. Quarantine and re-run three times in isolation.`,
    `3. **Coverage gaps** — ${gaps.length ? gaps.join(', ') : 'every suite type has at least one executed case'}.`,
    '',
    '### Execution strategy',
    '- Smoke suite on every change (target < 5 min).',
    '- Full regression nightly with a maximum of 3 parallel workers to protect a low-spec runner.',
    '- Accessibility and visual baselines on release candidates only.',
    '- Security header checks on every staging deploy.',
    '',
    '### Exit criteria',
    `- Pass rate >= 95% (current ${metrics.passRate}%).`,
    '- Zero critical-severity defects open.',
    '- No new flaky case above 20% failure rate.',
    `- Release readiness >= 85 (current ${metrics.readiness}).`,
  ].join('\n');
  res.json({ plan, metrics: { passRate: metrics.passRate, readiness: metrics.readiness, gaps } });
});

