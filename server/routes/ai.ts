function workspaceSummary(workspaceId: string): string {
  const m = computeMetrics(workspaceId);
  const db = getDb();
  return [
    `- Projects: ${m.projects}, suites: ${m.suites}, cases: ${m.cases}`,
    `- Pass rate: ${m.passRate}% across ${m.executed} executed case results`,
    `- Coverage (executed cases): ${m.coverage}%`,
    `- Open bugs: ${m.openBugs} (critical: ${m.criticalBugs})`,
    `- Flaky cases: ${m.flaky.length}`,
    `- Release readiness: ${m.readiness}/100`,
    `- AI provider: ${providerInfo().name}`,
    m.flaky.length ? `Top flaky: ${m.flaky.slice(0, 3).map((f) => `${f.title} (${f.rate}%)`).join(', ')}` : '',
    db.projects.map((p) => `- ${p.name} (${p.environment}) score ${p.qualityScore ?? 'n/a'}`).join('\n'),
  ]
    .filter(Boolean)
    .join('\n');
}

aiRouter.post('/chat', requireAuth, async (req: AuthedRequest, res) => {
  const parsed = z.object({ question: z.string().min(2).max(2000), projectId: z.string().optional() }).safeParse(req.body);
  if (!parsed.success) return res.status(400).json({ error: 'Ask a question first' });
  const { answer, provider } = await askAssistant(parsed.data.question, workspaceSummary(req.user!.workspaceId));
  res.json({ answer, provider, at: now() });
});

aiRouter.post('/generate-cases', requireAuth, requireRole('tester'), async (req: AuthedRequest, res) => {
  const parsed = z
    .object({
      requirement: z.string().min(10).max(4000),
      count: z.number().int().min(1).max(10).optional(),
      suiteId: z.string().optional(),
      requestApproval: z.boolean().optional(),
    })
    .safeParse(req.body);
  if (!parsed.success) return res.status(400).json({ error: 'Provide a requirement of at least 10 characters' });
  const db = getDb();
  const { cases, provider } = await generateCases(parsed.data.requirement, parsed.data.count ?? 6);
  const workspace = db.workspaces.find((w) => w.id === req.user!.workspaceId)!;
  let approvalId: string | undefined;

  const needsApproval = parsed.data.requestApproval ?? workspace.aiApprovalsRequired;
  if (needsApproval) {
    const approval = {
      id: id('apr'),
      workspaceId: workspace.id,
      kind: 'ai.case-generation',
      title: `Approve ${cases.length} AI-generated cases`,
      payload: { suiteId: parsed.data.suiteId, requirement: parsed.data.requirement, cases },
      requestedBy: req.user!.name,
      status: 'pending' as const,
      createdAt: now(),
    };
    db.approvals.unshift(approval);
    approvalId = approval.id;
  } else if (parsed.data.suiteId) {
    const suite = db.suites.find((s) => s.id === parsed.data.suiteId && s.workspaceId === workspace.id);
    if (suite) {
      for (const draft of cases) {
        db.cases.push({
          id: id('case'),
          workspaceId: workspace.id,
          projectId: suite.projectId,
          suiteId: suite.id,
          title: draft.title,
          type: suite.type,
          priority: draft.priority,
          automation: 'manual',
          steps: draft.steps,
          expected: draft.expected,
          tags: ['ai-generated', suite.type],
          timeoutMs: 15000,
          enabled: true,
          aiGenerated: true,
          version: 1,
          createdAt: now(),
          updatedAt: now(),
        });
      }
    }
  }
  saveDb();
  audit(workspace.id, req.user!.name, 'ai.cases_generated', undefined, { count: cases.length, provider, approvalId }, req.ip);
  res.json({ cases, provider, approvalId, requiresApproval: needsApproval });
});

aiRouter.post('/analyze-run', requireAuth, async (req: AuthedRequest, res) => {
  const parsed = z.object({ runId: z.string() }).safeParse(req.body);
  if (!parsed.success) return res.status(400).json({ error: 'runId is required' });
  const db = getDb();
  const run = db.runs.find((r) => r.id === parsed.data.runId && r.workspaceId === req.user!.workspaceId);
  if (!run) return res.status(404).json({ error: 'Run not found' });
  const failures = run.results.filter((r) => r.status === 'failed' || r.status === 'error');
  const { analysis, provider } = await analyseFailures(failures.map((f) => ({ title: f.title, message: f.message, type: f.type, durationMs: f.durationMs })));
  run.aiAnalysis = `${analysis}\n\n_Generated by ${provider} provider_`;
  saveDb();
  res.json({ analysis: run.aiAnalysis, provider });
});

