aiRouter.post('/approvals/:id', requireAuth, requireRole('qa_lead'), (req: AuthedRequest, res) => {
  const parsed = z.object({ decision: z.enum(['approved', 'rejected']) }).safeParse(req.body);
  if (!parsed.success) return res.status(400).json({ error: 'decision must be approved or rejected' });
  const db = getDb();
  const approval = db.approvals.find((a) => a.id === req.params.id && a.workspaceId === req.user!.workspaceId);
  if (!approval) return res.status(404).json({ error: 'Approval not found' });
  if (approval.status !== 'pending') return res.status(409).json({ error: 'Approval already decided' });
  approval.status = parsed.data.decision;
  approval.decidedBy = req.user!.name;
  approval.decidedAt = now();
  let applied = 0;

  if (parsed.data.decision === 'approved' && approval.kind === 'ai.case-generation') {
    const payload = approval.payload as { suiteId?: string; cases?: Array<{ title: string; type: string; priority: TestCase['priority']; steps: string[]; expected: string }> };
    const suite = payload.suiteId ? db.suites.find((s) => s.id === payload.suiteId) : db.suites.find((s) => s.workspaceId === req.user!.workspaceId);
    if (suite && payload.cases) {
      for (const draft of payload.cases) {
        db.cases.push({
          id: id('case'),
          workspaceId: req.user!.workspaceId,
          projectId: suite.projectId,
          suiteId: suite.id,
          title: draft.title,
          type: suite.type,
          priority: draft.priority,
          automation: 'manual',
          steps: draft.steps,
          expected: draft.expected,
          tags: ['ai-generated', suite.type],
          timeoutMs: 15000,
          enabled: true,
          aiGenerated: true,
          version: 1,
          createdAt: now(),
          updatedAt: now(),
        });
        applied += 1;
      }
    }
  }
  if (parsed.data.decision === 'approved' && approval.kind === 'ai.bug-drafts') {
    const payload = approval.payload as { bugs?: Array<{ title: string; description: string; severity: string; caseId?: string }>; projectId?: string };
    const project = payload.projectId ? db.projects.find((p) => p.id === payload.projectId) : db.projects.find((p) => p.workspaceId === req.user!.workspaceId);
    if (project && payload.bugs) {
      for (const draft of payload.bugs) {
        db.bugs.unshift({
          id: id('bug'),
          workspaceId: req.user!.workspaceId,
          projectId: project.id,
          title: draft.title,
          description: draft.description,
          severity: (draft.severity as 'low' | 'medium' | 'high' | 'critical') ?? 'high',
          status: 'open',
          linkedCaseId: draft.caseId,
          assignee: req.user!.name,
          aiRootCause: localFailureAnalysis([{ title: draft.title, message: draft.description }]),
          createdAt: now(),
          updatedAt: now(),
        });
        applied += 1;
      }
    }
  }
  saveDb();
  audit(req.user!.workspaceId, req.user!.name, `approval.${parsed.data.decision}`, approval.title, { applied }, req.ip);
  res.json({ approval, applied });
});
